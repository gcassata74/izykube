def detect_language() -> str:
    language, _encoding = locale.getlocale()
    code = (language or "").split("_", maxsplit=1)[0].lower()
    return code if code in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translate(language: str, key: str, **values: object) -> str:
    selected = language if language in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE
    try:
        text = TRANSLATIONS[selected][key]
    except KeyError as exception:
        raise KeyError(f"Missing {selected!r} translation for {key!r}") from exception
    return text.format(**values)
